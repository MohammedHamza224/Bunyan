import { Router, Response } from 'express';
import {
  authenticate,
  requirePermission,
  PERMISSIONS,
  AuthenticatedRequest,
} from '../middleware/auth';
import { testDataService } from '../services/testDataService';

const router = Router();

// All routes require authentication and MANAGE_SETTINGS permission
router.use(authenticate);
router.use(requirePermission(PERMISSIONS.MANAGE_SETTINGS));

/**
 * GET /api/test-data/datasets
 * List all test datasets for the user's organization.
 */
router.get('/datasets', async (req, res: Response) => {
  const authReq = req as AuthenticatedRequest;
  const datasets = await testDataService.listDatasets(authReq.user.organizationId);
  res.json({
    success: true,
    data: datasets,
  });
});

/**
 * GET /api/test-data/datasets/:id
 * Get details and entities for a specific test dataset.
 */
router.get('/datasets/:id', async (req, res: Response) => {
  const authReq = req as AuthenticatedRequest;
  const details = await testDataService.getDatasetDetails(
    authReq.user.organizationId,
    req.params.id
  );
  res.json({
    success: true,
    data: details,
  });
});

/**
 * POST /api/test-data/generate
 * Generate a new interconnected test dataset.
 */
router.post('/generate', async (req, res: Response) => {
  const authReq = req as AuthenticatedRequest;
  const { scenario, name, description } = req.body;

  const result = await testDataService.generateDataset(
    authReq.user.organizationId,
    authReq.user.id,
    { scenario, name, description }
  );

  res.status(201).json({
    success: true,
    data: result,
  });
});

/**
 * POST /api/test-data/datasets/:id/purge
 * Safely purge all records generated by a specific test dataset.
 */
router.post('/datasets/:id/purge', async (req, res: Response) => {
  const authReq = req as AuthenticatedRequest;
  const result = await testDataService.purgeDataset(
    authReq.user.organizationId,
    req.params.id,
    authReq.user.id
  );

  res.json({
    success: true,
    data: result,
  });
});

export default router;
